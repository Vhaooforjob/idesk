import AppKit
import Combine

@MainActor
final class ContextPresetService: ObservableObject {
    @Published private(set) var status = ""
    private let store: SettingsStore
    private let presets: PresetsViewModel
    private let journal: OperationJournal
    private var subscriptions: Set<AnyCancellable> = []
    private var topology = Set<String>()
    private var task: Task<Void, Never>?
    private var lastRuns: [String: Date] = [:]
    private var suppressedUntil = Date.distantPast
    private var sleeping = false
    private var pendingRule: ContextPresetRule?
    init(store: SettingsStore, presets: PresetsViewModel, journal: OperationJournal) {
        self.store = store; self.presets = presets; self.journal = journal
    }
    static func choose(rules: [ContextPresetRule], event: ContextPresetRule.Event, match: String,
                       lastRuns: [String: Date], now: Date) -> ContextPresetRule? {
        rules.filter {
            $0.isEnabled && ($0.event == event || (event != .appLaunched && $0.event == .topologyChanged)) && ($0.match.isEmpty || $0.match == match) &&
            now.timeIntervalSince(lastRuns[$0.id] ?? .distantPast) >= max(10, $0.cooldown)
        }.sorted { $0.priority == $1.priority ? $0.id < $1.id : $0.priority > $1.priority }.first
    }
    private func readTopology() -> Set<String> { Set(NSScreen.screens.compactMap { SpaceService.displayIdentifier(for: $0) }) }
    func start() {
        topology = readTopology()
        let center = NSWorkspace.shared.notificationCenter
        center.publisher(for: NSWorkspace.didLaunchApplicationNotification).sink { [weak self] note in
            guard let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
                  app.activationPolicy == .regular, let id = app.bundleIdentifier else { return }
            self?.receive(.appLaunched, match: id)
        }.store(in: &subscriptions)
        NotificationCenter.default.publisher(for: NSApplication.didChangeScreenParametersNotification).sink { [weak self] _ in
            guard let self else { return }
            let new = self.readTopology(), old = self.topology
            self.topology = new
            guard new != old else { return }
            let event: ContextPresetRule.Event = new.count > old.count ? .displayConnected : new.count < old.count ? .displayDisconnected : .topologyChanged
            self.receive(event, match: new.sorted().joined(separator: ","))
        }.store(in: &subscriptions)
        center.publisher(for: NSWorkspace.willSleepNotification).sink { [weak self] _ in self?.sleeping = true; self?.task?.cancel(); self?.pendingRule = nil }.store(in: &subscriptions)
        center.publisher(for: NSWorkspace.didWakeNotification).sink { [weak self] _ in
            self?.sleeping = false; self?.suppressedUntil = Date().addingTimeInterval(5)
            self?.topology = self?.readTopology() ?? []
        }.store(in: &subscriptions)
    }
    func stop() { task?.cancel(); pendingRule = nil; subscriptions.removeAll() }
    private func receive(_ event: ContextPresetRule.Event, match: String) {
        guard !sleeping, !store.value.workspace.automationPaused, !presets.isApplying, !presets.isSaving,
              Date() >= suppressedUntil,
              let rule = Self.choose(rules: store.value.workspace.contextRules, event: event, match: match, lastRuns: lastRuns, now: Date()) else { return }
        // Coalesce display storms; do not enqueue work generated by applying a session.
        if let pendingRule, pendingRule.priority > rule.priority { return }
        pendingRule = rule
        task?.cancel()
        task = Task { [weak self] in
            do { try await Task.sleep(for: .seconds(2)) } catch { return }
            guard let self else { return }
            self.pendingRule = nil
            guard !self.sleeping, !self.store.value.workspace.automationPaused,
                  self.store.value.workspace.contextRules.contains(rule),
                  !self.presets.isApplying, !self.presets.isSaving else { return }
            if event != .appLaunched && self.readTopology().sorted().joined(separator: ",") != match { return }
            guard let preset = self.presets.presets.first(where: { $0.id == rule.presetID }) else {
                self.status = String(localized: "Preset unavailable"); return
            }
            self.lastRuns[rule.id] = Date()
            self.suppressedUntil = Date().addingTimeInterval(10)
            do { try await self.presets.applyAndWait(preset); self.status = preset.name }
            catch { self.status = error.localizedDescription; self.journal.record("Context Preset", item: preset.name, error: error) }
            self.suppressedUntil = Date().addingTimeInterval(5)
            self.topology = self.readTopology()
        }
    }
}
